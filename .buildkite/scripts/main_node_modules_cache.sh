#!/bin/bash
# shellcheck disable=SC2034 # read by the preview_asset_cache.sh helpers called below
# Caches the production compile's node_modules in S3, keyed on what npm ci reads,
# so a main build whose lockfile did not change skips the install. Only main
# writes entries; main and comp-assets-* builds read them. Source
# preview_asset_cache.sh first: the S3 copy and checksum helpers come from it.

MAIN_NODE_MODULES_CACHE_PREFIX="main-node-modules"
MAIN_NODE_MODULES_CACHE_VERSION="v1"
# The directory compile_assets.sh mounts into the compile container (Makefile,
# build_production) as /node-modules-cache. It holds the restored tarball, and
# node_modules.tar.gz.new after an install the cache did not have.
MAIN_NODE_MODULES_CACHE_DIR=.main-node-modules-cache

# docker/base pins the Node version the install runs on; compile_assets.sh holds
# the npm ci flags and env.
main_node_modules_cache_tag() {
  local tree_sha
  tree_sha=$(git ls-tree -r HEAD -- package.json package-lock.json .npmrc patches docker/base docker/web/compile_assets.sh | sha1sum | cut -d " " -f1)
  echo "$tree_sha production $MAIN_NODE_MODULES_CACHE_VERSION" | sha1sum | cut -d " " -f1
}

# Leaves node_modules.tar.gz in the cache directory on a verified hit.
main_node_modules_cache_restore() {
  local tag=$1
  (
    PREVIEW_ASSET_CACHE_PREFIX=$MAIN_NODE_MODULES_CACHE_PREFIX
    PREVIEW_ASSET_CACHE_TARBALL=$MAIN_NODE_MODULES_CACHE_DIR/node_modules.tar.gz
    PREVIEW_ASSET_CACHE_CHECKSUM=$MAIN_NODE_MODULES_CACHE_DIR/node_modules.tar.gz.sha256
    preview_asset_cache_restore "$tag"
  )
}

# Best-effort: uploads the tarball the compile container wrote after npm ci, with
# the checksum sidecar that restore verifies. Upload order matches
# preview_asset_cache_save: tarball first, then sidecar.
main_node_modules_cache_save() {
  local tag=$1 tarball=$MAIN_NODE_MODULES_CACHE_DIR/node_modules.tar.gz.new
  [[ -s $tarball ]] || return 0
  (
    PREVIEW_ASSET_CACHE_PREFIX=$MAIN_NODE_MODULES_CACHE_PREFIX
    checksum=$tarball.sha256
    sha256sum "$tarball" | cut -d " " -f1 > "$checksum"
    if preview_asset_cache_s3_cp "$tarball" "$(preview_asset_cache_url "$tag")" \
      && preview_asset_cache_s3_cp "$checksum" "$(preview_asset_cache_url "$tag").sha256"; then
      preview_asset_cache_logger "Saved node_modules for tag $tag"
    else
      preview_asset_cache_logger "Could not save node_modules for tag $tag"
    fi
  )
}
