package sidekiq

import "math"

// grisu2 is fpconv's grisu2, appending f's digits to buf; k is the decimal exponent of the
// last digit. Grisu2 isn't a shortest-digits search, so now and then it gives a longer string
// than Float#to_s, and Ruby's JSON keeps that string.
func grisu2(f float64, buf []byte) (digits []byte, k int) {
	w := buildFp(f)
	lower, upper := normalizedBoundaries(w)
	w.normalize()
	cp, ck := cachedPow10(upper.exp)
	w, upper, lower = w.times(cp), upper.times(cp), lower.times(cp)
	lower.frac++
	upper.frac--
	k = -ck
	digits = generateDigits(w, upper, lower, &k, buf)
	return digits, k
}

type diyFp struct {
	frac uint64
	exp  int
}

