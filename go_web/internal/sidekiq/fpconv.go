func cachedPow10(exp int) (diyFp, int) {
	const oneLogTen = 0.30102999566398114
	approx := int(float64(-(exp + len(fpconvPowersTen))) * oneLogTen)
	idx := (approx - fpconvFirstPower) / fpconvStepPowers
	for {
		current := exp + fpconvPowersTen[idx].exp + 64
		switch {
		case current < fpconvExpMin:
			idx++
		case current > fpconvExpMax:
			idx--
		default:
			return fpconvPowersTen[idx], fpconvFirstPower + idx*fpconvStepPowers
		}
	}
}

func buildFp(f float64) diyFp {
	bits := math.Float64bits(f)
	fp := diyFp{frac: bits & fpconvFracMask, exp: int((bits & fpconvExpMask) >> 52)}
	if fp.exp != 0 {
		fp.frac += fpconvHiddenBit
		fp.exp -= fpconvExpBias
	} else {
		fp.exp = -fpconvExpBias + 1
	}
	return fp
}

func (fp *diyFp) normalize() {
	for fp.frac&fpconvHiddenBit == 0 {
		fp.frac <<= 1
		fp.exp--
	}
	const shift = 64 - 52 - 1
	fp.frac <<= shift
	fp.exp -= shift
}

func normalizedBoundaries(fp diyFp) (lower, upper diyFp) {
	upper = diyFp{frac: fp.frac<<1 + 1, exp: fp.exp - 1}
	for upper.frac&(fpconvHiddenBit<<1) == 0 {
		upper.frac <<= 1
		upper.exp--
	}
	const uShift = 64 - 52 - 2
	upper.frac <<= uShift
	upper.exp -= uShift
	lShift := 1
	if fp.frac == fpconvHiddenBit {
		lShift = 2
	}
	lower = diyFp{frac: fp.frac<<lShift - 1, exp: fp.exp - lShift}
	lower.frac <<= lower.exp - upper.exp
	lower.exp = upper.exp
	return lower, upper
}

func (a diyFp) times(b diyFp) diyFp {
	const lomask = 0x00000000FFFFFFFF
	ahBl := (a.frac >> 32) * (b.frac & lomask)
	alBh := (a.frac & lomask) * (b.frac >> 32)
	alBl := (a.frac & lomask) * (b.frac & lomask)
	ahBh := (a.frac >> 32) * (b.frac >> 32)
	tmp := (ahBl & lomask) + (alBh & lomask) + (alBl >> 32)
	tmp += 1 << 31
	return diyFp{frac: ahBh + (ahBl >> 32) + (alBh >> 32) + (tmp >> 32), exp: a.exp + b.exp + 64}
}

func roundDigit(digits []byte, delta, rem, kappa, frac uint64) {
	for rem < frac && delta-rem >= kappa && (rem+kappa < frac || frac-rem > rem+kappa-frac) {
		digits[len(digits)-1]--
		rem += kappa
	}
}

func generateDigits(fp, upper, lower diyFp, k *int, digits []byte) []byte {
	wfrac := upper.frac - fp.frac
	delta := upper.frac - lower.frac
	shift := uint(-upper.exp)
	one := uint64(1) << shift
	part1 := upper.frac >> shift
	part2 := upper.frac & (one - 1)
	kappa := 10
	for i := 10; kappa > 0; i++ {
		div := fpconvTens[i]
		digit := part1 / div
		if digit != 0 || len(digits) > 0 {
			digits = append(digits, byte(digit)+'0')
		}
		part1 -= digit * div
		kappa--
		if tmp := part1<<shift + part2; tmp <= delta {
			*k += kappa
			roundDigit(digits, delta, tmp, div<<shift, wfrac)
			return digits
		}
	}
	for unit := 18; ; unit-- {
		part2 *= 10
		delta *= 10
		kappa--
		if digit := part2 >> shift; digit != 0 || len(digits) > 0 {
			digits = append(digits, byte(digit)+'0')
		}
		part2 &= one - 1
		if part2 < delta {
			*k += kappa
			roundDigit(digits, delta, part2, one, wfrac*fpconvTens[unit])
			return digits
		}
	}
}
