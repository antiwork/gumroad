// Each want is what usd_cents_to_currency returned on the production console.
func TestUSDCentsToCurrency(t *testing.T) {
	for _, c := range []struct {
		currency string
		cents    int64
		rate     string
		want     int64
	}{
		{"eur", 1000, "0.92", 920}, {"jpy", 1000, "151.3", 1513}, {"gbp", 999, "0.785", 784}, {"inr", 12345, "83.1234", 1026158},
		{"krw", 1000, "1380.5", 1380500}, {"eur", 10, "1.15", 12}, {"eur", 10, "0.35", 4}, {"eur", 1, "0.5", 1},
		{"jpy", 50, "1.0", 1}, {"jpy", 150, "1.01", 2}, {"eur", 100, "1.005", 101}, {"eur", 7, "2.5", 18}, {"usd", 7, "", 7},
	} {
		if got, ok := usdCentsToCurrency(c.currency, c.cents, c.rate); !ok || got != c.want {
			t.Errorf("%v: %d", c, got)
		}
	}
	for _, rate := range []string{"", " ", "1e2", "inf", "1.2abc"} {
		if _, ok := usdCentsToCurrency("eur", 100, rate); ok {
			t.Errorf("rate %q converts", rate)
		}
	}
}
